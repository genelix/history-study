def generate_deep_description(event):
    title = event.get("title", "")
    summary = event.get("summary", "")
    significance = event.get("historical_significance", "")
    cause = event.get("cause", "")
    consequence = event.get("consequence", "")
    region = event.get("region_id", "")
    sub_region = event.get("sub_region", "")
    start_year = event.get("year_start", 0)
    end_year = event.get("year_end", 0)
    year_str = f"기원전 {abs(start_year)}년" if start_year < 0 else f"{start_year}년"
    if start_year != end_year:
        year_end_str = f"기원전 {abs(end_year)}년" if end_year < 0 else f"{end_year}년"
        year_str += f"부터 {year_end_str}까지"

    # Check curated keywords first
    for key, text in CURATED_NARRATIVES.items():
        if key in title:
            return text.strip()

    # Dynamic high-quality multi-paragraph narrative synthesis
    p1 = f"{year_str}, {sub_region or region} 권역에서 일어난 '{title}'은(는) 당대 문명사의 중대한 전환을 알리는 핵심 사건입니다."
    if cause:
        p1 += f" {cause}"
    else:
        p1 += f" 당시 정치·사회적 격변과 대내외적 역학 관계 속에서 문명 발전의 새로운 방향을 모색하는 과정에서 촉발되었습니다."

    p2 = f"사건의 핵심 전개 과정에서 {summary}"
    if consequence:
        p2 += f" 이로 인해 {consequence}"

    p3 = ""
    if significance:
        p3 = f"역사적 의의 측면에서, {significance} 이는 단일 지역의 변화에 그치지 않고 동시대 및 후대 문명의 제도, 문화, 사상적 진보에 깊은 발자취를 남겼습니다."
    else:
        p3 = f"이 사건은 당대 인류의 삶과 사회 구조를 근본적으로 재편하였으며, 오늘날까지 이어지는 역사적 연속성과 통섭적 지혜를 이해하는 데 있어 중요한 이정표로 평가받습니다."

    return f"{p1}\n\n{p2}\n\n{p3}".strip()

def main():
    if not os.path.exists(SEED_FILE):
        print(f"Error: {SEED_FILE} not found.")
        return

    with open(SEED_FILE, "r", encoding="utf-8") as f:
        events = json.load(f)

    updated_count = 0
    for ev in events:
        desc = generate_deep_description(ev)
        ev["detailed_description"] = desc
        updated_count += 1

    with open(SEED_FILE, "w", encoding="utf-8") as f:
        json.dump(events, f, ensure_ascii=False, indent=2)

    print(f"✅ Successfully enriched {updated_count} events with detailed_description in {SEED_FILE}")

if __name__ == "__main__":
    main()
