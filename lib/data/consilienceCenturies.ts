export function getConsilienceCenturyById(id: string): ConsiliencePeriod | undefined {
  return CONSILIENCE_CENTURIES.find((c) => c.id === id);
}

export function getConsilienceCenturyByYear(year: number): ConsiliencePeriod {
  let closest = CONSILIENCE_CENTURIES[0];
  let minDiff = Math.abs(year - closest.centerYear);
  for (const c of CONSILIENCE_CENTURIES) {
    const diff = Math.abs(year - c.centerYear);
    if (diff < minDiff) {
      minDiff = diff;
      closest = c;
    }
  }
  return closest;
}
